"""Build a compact discovery catalog from the same pinned JSON as community tags."""
import argparse
import collections
import datetime as dt
import hashlib
import json
import lzma
import struct
from pathlib import Path
from xml.sax.saxutils import escape
from steam_tag_table import entries, varint

ROOT = Path(__file__).resolve().parents[1]
REVISION = '6a31fcb42082345acc817e176b28849b7c05f248'
SHA256 = '6c5c8f7c119c4f3f38cf82944d79ae6f3ca9a433ce39685a9a98393108b50ef8'
EPOCH = dt.date(1900, 1, 1)


def release_day(value):
    for pattern in ('%b %d, %Y', '%d %b, %Y', '%B %d, %Y', '%Y-%m-%d'):
        try:
            day = (dt.datetime.strptime(value, pattern).date() - EPOCH).days + 1
            return day if day > 0 else 0
        except ValueError:
            pass
    return 0  # Partial dates and announcements are unknown, never invented dates.


def build(source, output, *, revision=REVISION, expected_sha256=SHA256,
          resource=ROOT / "app/src/main/res/values/steam_catalog_tags.xml"):
    with source.open('rb') as stream:
        assert hashlib.file_digest(stream, 'sha256').hexdigest() == expected_sha256, 'Source differs from pinned snapshot'
    rows = []
    tag_frequency = collections.Counter()
    for app_id, game in entries(source):
        name = game.get('name', '').strip()
        if not name:
            continue
        tags = game.get('tags', {})
        if isinstance(tags, dict):
            tag_frequency.update(tags.keys())
        score = game.get('metacritic_score', 0)
        positive, negative = int(game.get('positive', 0)), int(game.get('negative', 0))
        assert 0 < app_id <= 0x7fffffff and positive >= 0 and negative >= 0
        rows.append((app_id, name, score if 1 <= score <= 100 else 0,
                     release_day(game.get('release_date', '')), positive, positive + negative))
    rows.sort()
    raw = bytearray(b'STCA' + struct.pack('>ii', 1, len(rows)))
    previous = 0
    for app_id, name, score, day, positive, total in rows:
        title = name.encode('utf-8')
        raw += varint(app_id - previous) + varint(len(title)) + title + bytes([score])
        raw += varint(day) + varint(positive) + varint(total)
        previous = app_id
    # Verify every field with an independent sequential decode before publishing.
    offset, previous = 12, 0
    def integer():
        nonlocal offset
        value, shift = 0, 0
        while True:
            byte = raw[offset]; offset += 1
            value |= (byte & 127) << shift
            if byte < 128:
                return value
            shift += 7
    for row in rows:
        previous += integer()
        length = integer(); name = raw[offset:offset + length].decode('utf-8'); offset += length
        score = raw[offset]; offset += 1
        assert (previous, name, score, integer(), integer(), integer()) == row
    assert offset == len(raw)
    packed = lzma.compress(raw, check=lzma.CHECK_CRC32, preset=6)
    assert lzma.decompress(packed) == raw
    output.write_bytes(packed)
    # Compiled labels are available for the first frame, before catalog/index decoding or sorting.
    names = sorted(tag_frequency, key=lambda name: (-tag_frequency[name], name))
    def android_text(value):
        return escape(value.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"'))
    resource.write_text('<!-- Generated by scripts/build-steam-catalog.py from the pinned catalog source. -->\n'
                        '<resources>\n    <string-array name="steam_catalog_tag_names" translatable="false">\n'
                        + ''.join(f'        <item>{android_text(name)}</item>\n' for name in names)
                        + '    </string-array>\n</resources>\n')
    manifest = dict(format_version=1, source=f'https://huggingface.co/datasets/FronkonGames/steam-games-dataset/resolve/{revision}/games.json',
                    source_revision=revision, source_sha256=expected_sha256, source_license='MIT', games=len(rows),
                    with_metascore=sum(r[2] > 0 for r in rows), with_release_date=sum(r[3] > 0 for r in rows),
                    with_reviews=sum(r[5] > 0 for r in rows), uncompressed_bytes=len(raw), compressed_bytes=len(packed),
                    index_sha256=hashlib.sha256(packed).hexdigest())
    output.with_suffix('').with_suffix('.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--json', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=ROOT / 'app/src/main/assets/steam-catalog-v1.bin.xz')
    args = parser.parse_args()
    build(args.json, args.output)
